import assert from 'node:assert/strict';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import {
    assembleM4, TX2, encodeBinaryTape, decodeBinaryTape, TrapCircuit,
    scanAssemblySource, PLUGBOARD_WORDS, READER_LEADER_WORDS
} from '@sketchpad-lab/tx2-toolchain';
const source = '100|\nSTART→ LDA 200\nSTOP→ JMP STOP\n200|\n123\n☛☛PUNCH START';
const image = assembleM4(source,{autoAssign:false});
assert.deepEqual(image.diagnostics,[]);
const tape = encodeBinaryTape(image), decoded = decodeBinaryTape(tape);
assert.equal(tape.length,186);assert.equal(decoded.blocks.length,3);
const cpu = new TX2({profile:'tx2-io-research'});
cpu.bootTape(tape);cpu.breakpoints.add(image.entry);
assert.equal(cpu.P,0o377750);assert.equal(cpu.memory.peek(0o200),0n);
const initial=cpu.snapshot();
assert.equal(cpu.run({budget:250}).executed,250);
const checkpoint=cpu.snapshot();
const copy=new TX2({profile:'tx2-io-research'});copy.restore(checkpoint);copy.breakpoints.add(image.entry);
assert.equal(copy.run({budget:5000}).executed,399);
assert.equal(cpu.run({budget:5000}).executed,399);
assert.equal(cpu.P,0o100);assert.equal(cpu.cycles,649);
assert.deepEqual(cpu.snapshot(),copy.snapshot());
assert(cpu.step().ok);assert.equal(cpu.getRegister('A'),83n);
for(let i=0;i<650;i++)assert(cpu.back());
const reversed=cpu.snapshot();reversed.state.reason=initial.state.reason;
assert.deepEqual(reversed,initial);
const trap=new TrapCircuit();trap.connect(0o717);
assert.deepEqual(trap.access('operand',true,0o200,0o60,5),{mark:true,raise:true});
assert.equal(trap.count,1);trap.restore(trap.snapshot());
assert.equal(scanAssemblySource('[meta page=1]\n100|\nLDA [200]').lines[2].code,'LDA [200]');
assert.equal(PLUGBOARD_WORDS.length,32);assert.equal(READER_LEADER_WORDS.length,20);
const broken=tape.slice();broken[broken.length-12]^=1;
assert.throws(()=>decodeBinaryTape(broken),/checksum/i);
writeFileSync('program.tx2',source);
const cli='node_modules/@sketchpad-lab/tx2-toolchain/bin/assemble.mjs';
const valid=spawnSync(process.execPath,[cli,'--tape','--dialect','m4','--no-auto-assign','program.tx2','program.tape'],{encoding:'utf8'});
assert.equal(valid.status,0,valid.stderr);assert.deepEqual(new Uint8Array(readFileSync('program.tape')),tape);
writeFileSync('bad.tx2','UNDEFINED_THING');
writeFileSync('preserved.tape','KEEP');
const invalid=spawnSync(process.execPath,[cli,'--tape','bad.tx2','preserved.tape'],{encoding:'utf8'});
assert.equal(invalid.status,1);assert.equal(readFileSync('preserved.tape','utf8'),'KEEP');
writeFileSync('collision.tx2','.org 0\nLDA 100\n.org 100\n.word 1');
const collision=spawnSync(process.execPath,[cli,'--tape','collision.tx2','forbidden.tape'],{encoding:'utf8'});
assert.equal(collision.status,1);assert(!existsSync('forbidden.tape'));
writeFileSync('include-root.tx2','.include "fixture"\n.org 100\nLDA VALUE\n.org 200\n.word 7');
writeFileSync('fixture.inc','VALUE = 200');
const include=spawnSync(process.execPath,[cli,'--include','fixture=fixture.inc','include-root.tx2','included.json'],{encoding:'utf8'});
assert.equal(include.status,0,include.stderr);
const result={passed:true,version:JSON.parse(readFileSync('node_modules/@sketchpad-lab/tx2-toolchain/package.json','utf8')).version,offlineInstall:true,tests:['native M4/PUNCH','binary tape encoding/decoding','published bootstrap','independent snapshot/resume','complete reverse execution','TRAP circuit','lossless source view','numeric ROM/leader exports','checksum corruption','CLI binary byte identity','CLI compile failure preserves output','CLI tape failure creates no output','CLI explicit include binding'],bootInstructions:649,tapeBytes:186};
writeFileSync(process.env.PACKAGE_REPORT ?? 'installed-package-report.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
